class I18nManager {
  constructor() {
    this.currentLang = localStorage.getItem("signbridge_lang") || "en";
  }

  get lang() {
    return this.currentLang;
  }

  setLanguage(lang) {
    if (lang !== "en" && lang !== "ms") return;
    this.currentLang = lang;
    localStorage.setItem("signbridge_lang", lang);
    this.applyTranslations();
  }

  t(key) {
    const dict = TRANSLATIONS[this.currentLang] || TRANSLATIONS.en;
    return dict[key] || TRANSLATIONS.en[key] || key;
  }

  applyTranslations() {
    document.querySelectorAll("[data-i18n]").forEach(el => {
      const key = el.getAttribute("data-i18n");
      const translation = this.t(key);
      if (translation) {
        if (el.tagName === "INPUT" && el.placeholder) {
          el.placeholder = translation;
        } else {
          el.textContent = translation;
        }
      }
    });

    // Update active state on language pills
    document.querySelectorAll(".lang-btn").forEach(btn => {
      if (btn.dataset.lang === this.currentLang) {
        btn.classList.add("bg-white", "text-black", "font-bold");
        btn.classList.remove("text-zinc-400");
      } else {
        btn.classList.remove("bg-white", "text-black", "font-bold");
        btn.classList.add("text-zinc-400");
      }
    });

    // Dispatch custom event for modes to update their dynamic texts
    window.dispatchEvent(new CustomEvent("languageChanged", { detail: { lang: this.currentLang } }));
  }
}

export const i18n = new I18nManager();
